// Generates registry.json (consumed by `shadcn build`) and app/ds-tokens.css
// from components/ui, hooks, registry/tokens.mjs and registry/themes/*.json.
import { readdirSync, readFileSync, writeFileSync, existsSync } from "node:fs"
import { join, basename } from "node:path"
import { root, theme } from "../registry/tokens.mjs"

const BASE_URL =
  process.env.REGISTRY_URL ??
  "https://raw.githubusercontent.com/renanleonel/design-system/main/public/r"
const NAME = "renan"
const IGNORED_DEPS = new Set(["react", "react-dom", "next"])

const ref = (name) => `${BASE_URL}/${name}.json`

function pkgName(spec) {
  const parts = spec.split("/")
  return spec.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]
}

function analyze(path) {
  const src = readFileSync(path, "utf8")
  const dependencies = new Set()
  const registryDependencies = new Set()
  for (const [, spec] of src.matchAll(/from\s+["']([^"']+)["']/g)) {
    if (spec.startsWith("@/components/ui/")) registryDependencies.add(ref(basename(spec)))
    else if (spec === "@/lib/utils") registryDependencies.add(ref("utils"))
    else if (spec.startsWith("@/hooks/")) registryDependencies.add(ref(basename(spec)))
    else if (!spec.startsWith(".") && !spec.startsWith("@/")) {
      const pkg = pkgName(spec)
      if (!IGNORED_DEPS.has(pkg)) dependencies.add(pkg)
    }
  }
  return { dependencies: [...dependencies].sort(), registryDependencies: [...registryDependencies].sort() }
}

function fileItems(dir, type) {
  if (!existsSync(dir)) return []
  return readdirSync(dir)
    .filter((f) => /\.tsx?$/.test(f))
    .sort()
    .map((f) => {
      const path = join(dir, f).replaceAll("\\", "/")
      return {
        name: f.replace(/\.tsx?$/, ""),
        type,
        ...analyze(path),
        files: [{ path, type }],
      }
    })
}

const ui = fileItems("components/ui", "registry:ui")
const hooks = fileItems("hooks", "registry:hook")

const utils = {
  name: "utils",
  type: "registry:lib",
  dependencies: ["cn"],
  files: [{ path: "lib/utils.ts", type: "registry:lib" }],
}

const tokens = {
  name: "tokens",
  type: "registry:style",
  title: "Design tokens",
  description: "Layer-2 tokens (control size, control radius, shadows) on top of the shadcn theme contract.",
  cssVars: { theme, light: root },
}

const themesDir = "registry/themes"
const themes = existsSync(themesDir)
  ? readdirSync(themesDir)
      .filter((f) => f.endsWith(".json"))
      .sort()
      .map((f) => {
        const { $schema, name, ...rest } = JSON.parse(readFileSync(join(themesDir, f), "utf8"))
        return { ...rest, name: `theme-${f.replace(/\.json$/, "")}`, type: "registry:theme" }
      })
  : []

const base = {
  name: "base",
  type: "registry:base",
  title: "renan/ui",
  description: "Everything: tokens, default theme, utils and all components.",
  config: {
    style: "base-nova",
    iconLibrary: "lucide",
    tailwind: { baseColor: "neutral", cssVariables: true },
  },
  registryDependencies: [ref("utils"), ref("tokens"), ...ui.map((i) => ref(i.name))],
}

const registry = {
  $schema: "https://ui.shadcn.com/schema/registry.json",
  name: NAME,
  homepage: "https://github.com/renanleonel/design-system",
  items: [base, utils, tokens, ...themes, ...hooks, ...ui],
}
writeFileSync("registry.json", JSON.stringify(registry, null, 2) + "\n")

// Same tokens for the docs/playground app itself.
const decl = (obj, indent = "  ") =>
  Object.entries(obj).map(([k, v]) => `${indent}--${k}: ${v};`).join("\n")
writeFileSync(
  "app/ds-tokens.css",
  `/* Generated by scripts/gen-registry.mjs from registry/tokens.mjs. Do not edit. */\n` +
    `:root {\n${decl(root)}\n}\n\n@theme inline {\n${decl(theme)}\n}\n`
)

console.log(`registry.json: ${registry.items.length} items (${ui.length} ui, ${themes.length} themes)`)
